// Turns the approved concept art into web-ready plates for the 2.5D entrance and hub.
// Run with `npm run images` whenever design/concepts changes. Output is committed.
import { mkdir, writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const SRC = 'design/concepts'
const OUT = 'public/img'
const plates = { exterior: '01-exterior.png', doors: '02-doors.png', interior: '03-interior.png' }

await mkdir(OUT, { recursive: true })
const blur = {}
for (const [name, file] of Object.entries(plates)) {
  const src = sharp(`${SRC}/${file}`)
  await src.clone().webp({ quality: 82, effort: 6 }).toFile(`${OUT}/${name}.webp`)
  await src.clone().resize(640).webp({ quality: 72, effort: 6 }).toFile(`${OUT}/${name}-640.webp`)
  const tiny = await src.clone().resize(24).blur(1).webp({ quality: 50 }).toBuffer()
  blur[name] = `data:image/webp;base64,${tiny.toString('base64')}`
}
// Link preview: the doors.
await sharp(`${SRC}/02-doors.png`).resize(1200, 630, { fit: 'cover', position: 'top' }).jpeg({ quality: 80, mozjpeg: true }).toFile(`${OUT}/og.jpg`)
await writeFile('src/lib/blur.ts', `// generated by scripts/optimize-images.mjs\nexport const BLUR = ${JSON.stringify(blur, null, 2)} as const\n`)
console.log('done')
